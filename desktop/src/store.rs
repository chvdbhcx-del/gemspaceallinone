//! Accounts and settings, saved as JSON in the app's config folder. Account data (cookies, storage)
//! lives in <local data>/accounts/<id>, one WebView2 profile per account.

use std::collections::BTreeMap;
use std::fs;
use std::path::PathBuf;
use std::sync::atomic::{AtomicU32, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};
use tauri::{AppHandle, Manager};
use url::Url;

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
pub struct Account {
    pub id: String,
    pub name: String,
    pub color: String,
    #[serde(default)]
    pub proxy: Option<String>,
    /// never put to sleep
    #[serde(default)]
    pub pinned: bool,
}

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(default)]
pub struct Settings {
    pub sleep_enabled: bool,
    /// how many accounts stay loaded at most (pinned and the open one never sleep)
    pub max_awake: usize,
    pub notifications: bool,
    /// show the message text in notifications
    pub notify_preview: bool,
    pub close_to_tray: bool,
    /// interface size in percent, for the rail and the Gem Space pages (80..=150)
    pub ui_scale: u32,
    /// broadcasts (рассылка): messages one account may send in a day
    pub bc_limit: u32,
    /// broadcasts: random pause between two messages, in seconds
    pub bc_pause_min: u32,
    pub bc_pause_max: u32,
    /// the user has read the ban-risk warning
    pub bc_warned: bool,
}

pub const BC_LIMIT_MAX: u32 = 300;
pub const BC_PAUSE_FLOOR: u32 = 10;

impl Settings {
    /// Keeps the broadcast limits sane whatever the rail or a backup file says.
    pub fn clamp(&mut self) {
        self.max_awake = self.max_awake.clamp(1, 60);
        self.ui_scale = self.ui_scale.clamp(80, 150);
        self.bc_limit = self.bc_limit.clamp(1, BC_LIMIT_MAX);
        self.bc_pause_min = self.bc_pause_min.clamp(BC_PAUSE_FLOOR, 600);
        self.bc_pause_max = self.bc_pause_max.clamp(self.bc_pause_min, 900);
    }
}

impl Default for Settings {
    fn default() -> Self {
        Self {
            sleep_enabled: true,
            max_awake: 8,
            notifications: true,
            notify_preview: true,
            close_to_tray: true,
            ui_scale: 100,
            bc_limit: 50,
            bc_pause_min: 25,
            bc_pause_max: 70,
            bc_warned: false,
        }
    }
}

pub use crate::crm::{clean_color, clean_labels, clean_name, ChatMeta, Label, Template};
use crate::crm::{default_statuses, merge_templates, safe_id};

#[derive(Serialize, Deserialize, Clone, Debug)]
#[serde(default)]
pub struct Store {
    pub accounts: Vec<Account>,
    pub active: Option<String>,
    pub settings: Settings,
    pub labels: Vec<Label>,
    /// "<account id>|<chat name>" -> label ids
    pub chat_labels: BTreeMap<String, Vec<String>>,
    /// accounts whose data folder still has to be deleted
    pub pending_delete: Vec<String>,
    /// broadcast messages sent today per account, for the daily limit; `sent_day` is "YYYY-MM-DD" (UTC)
    pub sent_day: String,
    pub sent: BTreeMap<String, u32>,
    /// notes, statuses and reminders of chats (crm.rs); a state file from before them gets the default statuses
    #[serde(flatten)]
    pub meta: ChatMeta,
    /// quick-reply templates
    pub templates: Vec<Template>,
}

impl Default for Store {
    fn default() -> Self {
        Store {
            accounts: Vec::new(),
            active: None,
            settings: Settings::default(),
            labels: Vec::new(),
            chat_labels: BTreeMap::new(),
            pending_delete: Vec::new(),
            sent_day: String::new(),
            sent: BTreeMap::new(),
            meta: ChatMeta { statuses: default_statuses(), ..Default::default() },
            templates: Vec::new(),
        }
    }
}

fn state_file(app: &AppHandle) -> tauri::Result<PathBuf> {
    Ok(app.path().app_config_dir()?.join("state.json"))
}

pub fn account_dir(app: &AppHandle, id: &str) -> tauri::Result<PathBuf> {
    // ids are generated by new_id(): [0-9a-z-] only, so they are safe as a folder name
    Ok(app.path().app_local_data_dir()?.join("accounts").join(id))
}

impl Store {
    pub fn load(app: &AppHandle) -> Store {
        let Ok(path) = state_file(app) else { return Store::default() };
        match fs::read_to_string(&path) {
            Ok(s) => Store::parse(&s)
                .unwrap_or_else(|e| {
                    eprintln!("gemspace: {} is broken ({e}), starting empty", path.display());
                    let _ = fs::copy(&path, path.with_extension("json.broken"));
                    Store::default()
                }),
            Err(_) => Store::default(),
        }
    }

    /// The state file's text; one written before statuses existed gets the default ones.
    pub fn parse(s: &str) -> serde_json::Result<Store> {
        let raw: serde_json::Value = serde_json::from_str(s)?;
        let fresh = raw.get("statuses").is_none();
        let mut st: Store = serde_json::from_value(raw)?;
        if fresh {
            st.meta.statuses = default_statuses();
        }
        st.settings.clamp();
        Ok(st)
    }

    pub fn save(&self, app: &AppHandle) -> Result<(), String> {
        let path = state_file(app).map_err(|e| e.to_string())?;
        if let Some(dir) = path.parent() {
            fs::create_dir_all(dir).map_err(|e| e.to_string())?;
        }
        let tmp = path.with_extension("json.tmp");
        fs::write(&tmp, serde_json::to_vec_pretty(self).map_err(|e| e.to_string())?).map_err(|e| e.to_string())?;
        fs::rename(&tmp, &path).map_err(|e| e.to_string())
    }
}

/// The file "Резервная копия" writes: accounts (without logins), settings and labels. The same format on
/// Windows and Android; settings are taken only from a file made on the same kind of device.
#[derive(Serialize, Deserialize, Debug)]
pub struct Backup {
    pub app: String,
    pub format: u32,
    pub platform: String,
    #[serde(default)]
    pub accounts: Vec<Account>,
    #[serde(default)]
    pub settings: serde_json::Value,
    #[serde(default)]
    pub labels: Vec<Label>,
    #[serde(default)]
    pub chat_labels: BTreeMap<String, Vec<String>>,
    /// notes, statuses and reminders (files from before them have none)
    #[serde(default, flatten)]
    pub meta: ChatMeta,
    #[serde(default)]
    pub templates: Vec<Template>,
}

pub const BACKUP_APP: &str = "hovi-space";

impl Store {
    pub fn backup(&self) -> Backup {
        Backup {
            app: BACKUP_APP.into(),
            format: 1,
            platform: "windows".into(),
            accounts: self.accounts.clone(),
            settings: serde_json::to_value(&self.settings).unwrap_or_default(),
            labels: self.labels.clone(),
            chat_labels: self.chat_labels.clone(),
            meta: self.meta.clone(),
            templates: self.templates.clone(),
        }
    }

    /// Adds the file's accounts (an account already here by the same id gets its name, colour, proxy and
    /// "не усыплять" from the file), its labels and, from a Windows file, its settings. Returns (added, updated).
    pub fn restore(&mut self, b: Backup) -> Result<(usize, usize), String> {
        if b.app != BACKUP_APP || b.format != 1 {
            return Err("Это не резервная копия Hovi Space".into());
        }
        let (mut added, mut updated) = (0, 0);
        let mut renamed: BTreeMap<String, String> = BTreeMap::new();
        for a in b.accounts.into_iter().take(200) {
            let name = clean_name(&a.name, 40);
            let name = if name.is_empty() { format!("Аккаунт {}", self.accounts.len() + 1) } else { name };
            let color = clean_color(&a.color);
            let proxy = a.proxy.filter(|p| parse_proxy(p).is_ok());
            if let Some(mine) = self.accounts.iter_mut().find(|m| m.id == a.id) {
                mine.name = name;
                mine.color = color;
                mine.proxy = proxy;
                mine.pinned = a.pinned;
                updated += 1;
            } else {
                let id = if safe_id(&a.id) && !self.pending_delete.contains(&a.id) { a.id.clone() } else { new_id() };
                if id != a.id {
                    renamed.insert(a.id.clone(), id.clone());
                }
                self.accounts.push(Account { id, name, color, proxy, pinned: a.pinned });
                added += 1;
            }
        }
        if b.platform == "windows" {
            if let Ok(s) = serde_json::from_value::<Settings>(b.settings) {
                self.settings = s;
                self.settings.clamp();
            }
        }
        let mut labels = self.labels.clone();
        for l in b.labels {
            match labels.iter_mut().find(|x| x.id == l.id) {
                Some(x) => *x = l,
                None => labels.push(l),
            }
        }
        // a chat key gets the id its account has here
        let rekey = |key: &str| -> Option<String> {
            let (acc, chat) = key.split_once('|')?;
            Some(match renamed.get(acc) {
                Some(new) => format!("{new}|{chat}"),
                None => key.to_string(),
            })
        };
        let mut chat_labels = self.chat_labels.clone();
        for (key, ids) in b.chat_labels {
            let Some(key) = rekey(&key) else { continue };
            let slot = chat_labels.entry(key).or_default();
            for i in ids {
                if !slot.contains(&i) {
                    slot.push(i);
                }
            }
        }
        let (labels, chat_labels) = clean_labels(labels, chat_labels);
        self.labels = labels;
        self.chat_labels = chat_labels;
        self.meta.merge(b.meta, rekey);
        self.templates = merge_templates(&self.templates, b.templates);
        Ok((added, updated))
    }
}

/// Deletes the data folders of removed accounts; a folder still in use stays on the list for the next start.
pub fn purge_deleted(app: &AppHandle) {
    let state = app.state::<crate::AppState>();
    let pending = state.store.lock().unwrap().pending_delete.clone();
    if pending.is_empty() {
        return;
    }
    let mut left = Vec::new();
    for id in pending {
        let valid = !id.is_empty() && id.chars().all(|c| c.is_ascii_alphanumeric() || c == '-');
        let Ok(dir) = account_dir(app, &id) else { continue };
        if valid && dir.exists() && fs::remove_dir_all(&dir).is_err() {
            left.push(id);
        }
    }
    let mut store = state.store.lock().unwrap();
    store.pending_delete = left;
    let _ = store.save(app);
}

static COUNTER: AtomicU32 = AtomicU32::new(0);

pub fn new_id() -> String {
    let ms = SystemTime::now().duration_since(UNIX_EPOCH).map(|d| d.as_millis()).unwrap_or(0);
    format!("{}-{}", radix36(ms), COUNTER.fetch_add(1, Ordering::Relaxed))
}

fn radix36(mut n: u128) -> String {
    const D: &[u8] = b"0123456789abcdefghijklmnopqrstuvwxyz";
    if n == 0 {
        return "0".into();
    }
    let mut out = Vec::new();
    while n > 0 {
        out.push(D[(n % 36) as usize]);
        n /= 36;
    }
    out.reverse();
    String::from_utf8(out).unwrap()
}

/// Accepts "socks5://host:port", "http://host:port" or a bare "host:port" (taken as HTTP).
pub fn parse_proxy(s: &str) -> Result<Url, String> {
    let s = s.trim();
    let full = if s.contains("://") { s.to_string() } else { format!("http://{s}") };
    let url = Url::parse(&full).map_err(|_| format!("Не понял адрес прокси: {s}"))?;
    if !matches!(url.scheme(), "http" | "socks5") {
        return Err("Прокси должен быть http:// или socks5://".into());
    }
    if url.host_str().is_none() || url.port().is_none() {
        return Err("Укажите прокси как хост:порт, например socks5://1.2.3.4:1080".into());
    }
    if !url.username().is_empty() {
        return Err("Прокси с логином и паролем WebView2 не поддерживает, нужен прокси без авторизации".into());
    }
    Ok(url)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn proxies() {
        assert_eq!(parse_proxy("1.2.3.4:8080").unwrap().as_str(), "http://1.2.3.4:8080/");
        assert!(parse_proxy("socks5://h:1080").is_ok());
        assert!(parse_proxy("ftp://h:1").is_err());
        assert!(parse_proxy("socks5://u:p@h:1080").is_err());
        assert!(parse_proxy("host").is_err());
    }

    fn acc(id: &str, name: &str) -> Account {
        Account { id: id.into(), name: name.into(), color: "#26a69a".into(), proxy: None, pinned: false }
    }

    #[test]
    fn backup_round_trip() {
        let mut a = Store { accounts: vec![acc("k1-0", "Продажи"), acc("k2-1", "Поддержка")], ..Default::default() };
        a.settings.max_awake = 5;
        a.labels = vec![Label { id: "l1".into(), name: "Клиенты".into(), color: "#ff4d4d".into() }];
        a.chat_labels.insert("k1-0|Ирина".into(), vec!["l1".into()]);
        let file = serde_json::to_string(&a.backup()).unwrap();

        let mut b = Store { accounts: vec![acc("k2-1", "Старое имя")], ..Default::default() };
        let (added, updated) = b.restore(serde_json::from_str(&file).unwrap()).unwrap();
        assert_eq!((added, updated), (1, 1));
        assert_eq!(b.accounts.iter().map(|x| x.name.as_str()).collect::<Vec<_>>(), ["Поддержка", "Продажи"]);
        assert_eq!(b.settings.max_awake, 5);
        assert_eq!(b.labels.len(), 1);
        assert_eq!(b.chat_labels.get("k1-0|Ирина"), Some(&vec!["l1".to_string()]));
    }

    #[test]
    fn old_state_files_get_statuses() {
        let old = Store::parse(r##"{"accounts":[{"id":"k1-0","name":"Продажи","color":"#26a69a"}],"labels":[]}"##).unwrap();
        assert_eq!(old.meta.statuses.len(), 3);
        assert!(old.templates.is_empty());
        let mut s = Store::default();
        s.meta.statuses.clear(); // the user deleted them all: they stay deleted
        s.meta.notes.insert("k1-0|Ирина".into(), "VIP".into());
        s.templates.push(Template { id: "t1".into(), title: "Привет".into(), text: "Здравствуйте!".into() });
        let back = Store::parse(&serde_json::to_string(&s).unwrap()).unwrap();
        assert!(back.meta.statuses.is_empty());
        assert_eq!(back.meta.notes.get("k1-0|Ирина").map(String::as_str), Some("VIP"));
        assert_eq!(back.templates.len(), 1);
    }

    #[test]
    fn backup_carries_notes_statuses_and_templates() {
        let mut a = Store { accounts: vec![acc("k1-0", "Продажи")], ..Default::default() };
        a.meta.notes.insert("k1-0|Ирина".into(), "перезвонить".into());
        a.meta.chat_status.insert("k1-0|Ирина".into(), "s-wait".into());
        a.meta.reminders.insert("k1-0|Ирина".into(), 1_800_000_000_000);
        a.templates.push(Template { id: "t1".into(), title: "Привет".into(), text: "Здравствуйте, {имя}!".into() });
        let file = serde_json::to_string(&a.backup()).unwrap();
        let mut b = Store::default();
        b.restore(serde_json::from_str(&file).unwrap()).unwrap();
        assert_eq!(b.meta.notes.get("k1-0|Ирина").map(String::as_str), Some("перезвонить"));
        assert_eq!(b.meta.chat_status.get("k1-0|Ирина").map(String::as_str), Some("s-wait"));
        assert_eq!(b.meta.reminders.get("k1-0|Ирина"), Some(&1_800_000_000_000));
        assert_eq!(b.templates.len(), 1);
        // a file from before these existed still restores
        let old: Backup = serde_json::from_str(r#"{"app":"hovi-space","format":1,"platform":"windows","accounts":[]}"#).unwrap();
        assert!(b.restore(old).is_ok());
        assert_eq!(b.meta.statuses.len(), 3);
    }

    #[test]
    fn backup_rejects_and_cleans() {
        let mut s = Store::default();
        let bad: Backup = serde_json::from_str(r#"{"app":"other","format":1,"platform":"windows"}"#).unwrap();
        assert!(s.restore(bad).is_err());
        let odd: Backup = serde_json::from_str(r##"{"app":"hovi-space","format":1,"platform":"android",
            "settings":{"max_awake":2},
            "accounts":[{"id":"../x","name":"  ","color":"red","proxy":"ftp://h:1","pinned":true}],
            "labels":[{"id":"l1","name":"Оплата","color":"#00ff00"},{"id":"bad id","name":"x","color":"#000000"}],
            "chat_labels":{"../x|Чат":["l1","nope"],"nobar":["l1"]}}"##).unwrap();
        assert_eq!(s.restore(odd).unwrap(), (1, 0));
        let a = &s.accounts[0];
        assert!(safe_id(&a.id) && a.id != "../x");
        assert_eq!((a.color.as_str(), a.proxy.is_none(), a.pinned), ("#3aa0ff", true, true));
        assert_eq!(s.settings.max_awake, Settings::default().max_awake); // an Android file keeps these settings
        assert_eq!(s.labels.len(), 1);
        assert_eq!(s.chat_labels.get(&format!("{}|Чат", a.id)), Some(&vec!["l1".to_string()]));
        assert_eq!(s.chat_labels.len(), 1);
    }

    #[test]
    fn names_colours_and_settings_are_kept_sane() {
        assert_eq!(clean_name("  Продажи  ", 40), "Продажи");
        assert_eq!(clean_name(&"я".repeat(50), 40).chars().count(), 40);
        assert_eq!(clean_color("#FF4D4D"), "#ff4d4d");
        assert_eq!(clean_color("red;background:url(x)"), "#3aa0ff");
        let mut s = Settings { max_awake: 0, ui_scale: 500, bc_pause_min: 1, bc_pause_max: 5, bc_limit: 0, ..Settings::default() };
        s.clamp();
        assert_eq!((s.max_awake, s.ui_scale, s.bc_pause_min, s.bc_pause_max, s.bc_limit), (1, 150, 10, 10, 1));
    }

    #[test]
    fn ids_are_folder_safe() {
        let a = new_id();
        let b = new_id();
        assert_ne!(a, b);
        assert!(a.chars().all(|c| c.is_ascii_alphanumeric() || c == '-'));
    }
}
